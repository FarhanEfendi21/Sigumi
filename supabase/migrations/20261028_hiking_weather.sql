-- Cache prakiraan dan peringatan BMKG. Semua tabel hanya diakses backend
-- Edge Function memakai service role; tidak ada akses langsung dari klien.
CREATE TABLE IF NOT EXISTS public.hiking_weather_cache (
  adm4 TEXT PRIMARY KEY,
  area_name TEXT NOT NULL,
  analysis_date TIMESTAMPTZ,
  fetched_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  expires_at TIMESTAMPTZ NOT NULL,
  payload JSONB NOT NULL
);

ALTER TABLE public.hiking_weather_cache ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS public.hiking_weather_alerts (
  identifier TEXT PRIMARY KEY,
  revision TEXT NOT NULL,
  headline TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  severity TEXT NOT NULL DEFAULT 'Unknown',
  urgency TEXT NOT NULL DEFAULT 'Unknown',
  effective_at TIMESTAMPTZ,
  expires_at TIMESTAMPTZ,
  area_desc TEXT NOT NULL DEFAULT '',
  polygons JSONB NOT NULL DEFAULT '[]'::JSONB,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.hiking_weather_alerts ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS public.hiking_weather_alert_deliveries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alert_identifier TEXT NOT NULL,
  alert_revision TEXT NOT NULL,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  session_id UUID NOT NULL REFERENCES public.hiking_sessions(id) ON DELETE CASCADE,
  sent_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (alert_identifier, alert_revision, user_id, session_id)
);

ALTER TABLE public.hiking_weather_alert_deliveries ENABLE ROW LEVEL SECURITY;

-- Tabel ini sudah digunakan oleh NotificationService untuk menyimpan token.
-- Definisi idempoten memastikan deployment baru memiliki struktur yang sama.
CREATE TABLE IF NOT EXISTS public.user_notification_preferences (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  fcm_token TEXT NOT NULL UNIQUE,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.user_notification_preferences ENABLE ROW LEVEL SECURITY;
CREATE UNIQUE INDEX IF NOT EXISTS idx_user_notification_preferences_fcm_token
  ON public.user_notification_preferences (fcm_token);
DROP POLICY IF EXISTS "Users manage own notification tokens"
  ON public.user_notification_preferences;
DROP POLICY IF EXISTS "Users view own notification tokens"
  ON public.user_notification_preferences;
CREATE POLICY "Users view own notification tokens"
  ON public.user_notification_preferences FOR SELECT
  USING (auth.uid() = user_id);
DROP POLICY IF EXISTS "Users insert own notification tokens"
  ON public.user_notification_preferences;
CREATE POLICY "Users insert own notification tokens"
  ON public.user_notification_preferences FOR INSERT
  WITH CHECK (auth.uid() = user_id);
DROP POLICY IF EXISTS "Users update own notification tokens"
  ON public.user_notification_preferences;
CREATE POLICY "Users update own notification tokens"
  ON public.user_notification_preferences FOR UPDATE
  USING (auth.uid() = user_id OR user_id IS NULL)
  WITH CHECK (auth.uid() = user_id);
DROP POLICY IF EXISTS "Users delete own notification tokens"
  ON public.user_notification_preferences;
CREATE POLICY "Users delete own notification tokens"
  ON public.user_notification_preferences FOR DELETE
  USING (auth.uid() = user_id);

CREATE INDEX IF NOT EXISTS idx_hiking_weather_alerts_active
  ON public.hiking_weather_alerts (expires_at);
CREATE INDEX IF NOT EXISTS idx_hiking_weather_delivery_user
  ON public.hiking_weather_alert_deliveries (user_id, sent_at DESC);
