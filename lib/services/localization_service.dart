  /// Dapatkan string terjemahan berdasarkan kunci dan bahasa
  static String translate(String key, String language) {
    final lang = language.toLowerCase();

    if (!translations.containsKey(lang)) {
      // Fallback ke Indonesian jika bahasa tidak tersedia
      return translations['id']?[key] ?? _additionalTranslations['id']?[key] ?? key;
    }

    return translations[lang]?[key] ??
        _additionalTranslations[lang]?[key] ??
        _additionalTranslations['en']?[key] ??
        key;
  }

  static String translateText(String sourceText, String language) {
    final lang = language.toLowerCase();
    if (lang == 'id') return sourceText;

    final directTranslation = translations[lang]?[sourceText] ??
        _additionalTranslations[lang]?[sourceText];
    if (directTranslation != null) return directTranslation;

    for (final entry in translations['id']!.entries) {
      if (entry.value == sourceText) {
        return translations[lang]?[entry.key] ??
            _additionalTranslations[lang]?[entry.key] ??
            _additionalTranslations['en']?[entry.key] ??
            sourceText;
      }
    }
    for (final entry in _additionalTranslations['id']!.entries) {
      if (entry.value == sourceText) {
        return _additionalTranslations[lang]?[entry.key] ??
            _additionalTranslations['en']?[entry.key] ??
            sourceText;
      }
    }

    final normalized = sourceText.replaceAll(RegExp(r'\s+'), ' ').trim();
    return _literalTranslations[lang]?[normalized] ??
        _literalTranslations['en']?[normalized] ??
        sourceText;
